/** Cleans one shop attribute name: leftovers like " Удалити", "2" at the end, double spaces. */
function clean(name) {
  return String(name)
    .replace(/\s+Удалити$/i, '')
    .replace(/(?<=\p{L})2$/u, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** The catalog's name for a shop's Ukrainian attribute name; null = not exported. */
export function canonicalAttribute(name) {
  if (Object.hasOwn(SYNONYMS, name)) return SYNONYMS[name];
  const cleaned = clean(name);
  if (Object.hasOwn(SYNONYMS, cleaned)) return SYNONYMS[cleaned];
  return cleaned || null;
}

/** Values: trimmed, no doubled spaces, "Так"/"Ні" kept as they are. */
export function cleanValue(value) {
  return String(value ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\s*;\s*/g, '; ')
    .trim();
}

