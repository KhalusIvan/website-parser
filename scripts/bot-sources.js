// Writes bot/sources.generated.js: the list of websites (names, languages, modes) for the Telegram bot.
// The bot runs on Cloudflare Workers and can't load the scrapers themselves, only this list.
// Run after adding a source: npm run bot:sources (bot:deploy runs it too).
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describeSources } from '../src/sources/index.js';

export const GENERATED_FILE = new URL('../bot/sources.generated.js', import.meta.url);

export function renderSources() {
  return `// Generated by scripts/bot-sources.js from src/sources - do not edit by hand.
export default ${JSON.stringify(describeSources(), null, 2)};
`;
}

if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] ?? '')) {
  await writeFile(GENERATED_FILE, renderSources());
  console.log(`Wrote ${fileURLToPath(GENERATED_FILE)}`);
}
